def build_bag(amounts):
    """Return the ``背包素材`` dict for the BiliWiki calculator.

    :param amounts: {Amenoma Chinese material name: amount}
    """
    bag = {key: 0 for key in BILIWIKI_BAG_KEYS}
    for name, amount in amounts.items():
        key = NAME_ALIASES.get(name, name)
        if key in bag:
            bag[key] = amount
    return bag
